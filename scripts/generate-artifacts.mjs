// Generate every derived artifact from artifacts.json, the single source.
//
// The problem this solves: the package name, the plugin config, the skill count
// in the README and the skill list in the tests were all repeated by hand, so a
// rename or a newly synced skill silently desynchronised them. Everything that
// can be derived is now derived.
//
// Usage:
//   node scripts/generate-artifacts.mjs           # write
//   node scripts/generate-artifacts.mjs --check   # exit 1 if anything drifted
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ownContentInSkillsTree } from './lib/own-content.mjs'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')

const manifest = JSON.parse(readFileSync(join(packageRoot, 'artifacts.json'), 'utf8'))
const pkg = JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8'))

/**
 * System-prompt section order for the bootstrap, read out of index.js rather
 * than repeated here. It is fixed rather than configurable (so it is not part of
 * the config surface), and this README row is derived from the code that
 * actually mounts the section.
 */
function bootstrapSectionOrder() {
  const source = readFileSync(join(packageRoot, 'index.js'), 'utf8')
  const match = source.match(/const BOOTSTRAP_SECTION_ORDER = (\d+)/)
  if (match === null) {
    throw new Error('index.js no longer defines BOOTSTRAP_SECTION_ORDER — update this generator')
  }
  return Number(match[1])
}
const BOOTSTRAP_ORDER = bootstrapSectionOrder()

/** Pending writes, applied only after every generator succeeds. */
const writes = []
/** Human-readable description of each artifact, for the report. */
const produced = []

/** Record a write (or a drift finding under --check). */
function emit(relPath, content) {
  const full = join(packageRoot, relPath)
  const current = existsSync(full) ? readFileSync(full, 'utf8') : undefined
  if (checkOnly) {
    if (current !== content) {
      produced.push(`DRIFT  ${relPath}`)
      return false
    }
    produced.push(`ok     ${relPath}`)
    return true
  }
  if (current !== content) {
    writes.push({ full, content })
    produced.push(`write  ${relPath}`)
  } else {
    produced.push(`same   ${relPath}`)
  }
  return true
}

/** List skill directories, sorted, skipping dotfiles. */
function listSkills(root) {
  return readdirSync(join(packageRoot, root), { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .sort()
}

// Own skills are declared in the manifest, not discovered from the tree: on a
// fresh sync the copies below have not run yet, so a directory scan would miss
// them and the generated table/tests would undercount.
const own = new Set(manifest.skillTree.own)
const upstreamSkills = listSkills(manifest.skillTree.root).filter((s) => !own.has(s))
const allSkills = [...upstreamSkills, ...[...own].sort()]

// ---------------------------------------------------------------------------
// cordis.patch.yml — the bundle row, derived from the package name + config
// ---------------------------------------------------------------------------

function renderPatch() {
  const { defaults, description } = manifest.config
  const lines = []
  lines.push('# Cordis bundle patch for DeepSeek Harness profiles.')
  lines.push('#')
  lines.push('# GENERATED by scripts/generate-artifacts.mjs from artifacts.json.')
  lines.push('# Do not edit by hand: run `node scripts/generate-artifacts.mjs` instead.')
  lines.push('#')
  lines.push('# Applied automatically when this package is installed through dsh\'s own')
  lines.push('# plugin command — for example')
  lines.push('#')
  lines.push(`#   dsh plugin --profile web add ${pkg.name}`)
  lines.push('#   dsh plugin --profile web add link:/path/to/this-package')
  lines.push('#')
  lines.push('# The dsh CLI appends every dependency that declares `dsh.bundle`')
  lines.push('# (see package.json) to the profile\'s `dsh.profile.bundles`, and each')
  lines.push('# bundle\'s patch is layered into the composed configuration at boot.')
  lines.push('# Nothing here edits a user\'s config: the install artifact is the install.')
  lines.push('#')
  lines.push('# The row mounts `index.js`, which')
  lines.push('#   1. serves this package\'s vendored `skills/` tree through dsh\'s OWN')
  lines.push('#      `@deepseek-ai/dsh-skill-filesystem` provider (a private instance at')
  lines.push('#      `bundledSkillDir`, rank 600), so the skills load with dsh\'s native')
  lines.push('#      `skill` tool and inherit that provider\'s parsing, watching and fixes; and')
  lines.push('#   2. contributes the `using-superpowers` bootstrap — with the dsh tool')
  lines.push('#      mapping — as the `superpowers:bootstrap` system-prompt section.')
  lines.push('')
  lines.push('- insert:')
  lines.push('    - id: superpowers')
  lines.push(`      name: '${pkg.name}'`)
  lines.push('      config:')
  for (const [key, value] of Object.entries(defaults)) {
    if (description[key]) lines.push(`        # ${description[key]}`)
    lines.push(`        ${key}: ${JSON.stringify(value)}`)
  }
  lines.push('')
  return lines.join('\n')
}

// ---------------------------------------------------------------------------
// Generated regions inside hand-written files
// ---------------------------------------------------------------------------

/** Replace the text between marker comments, keeping the markers. */
function replaceRegion(source, { begin, end }, body) {
  const beginAt = source.indexOf(begin)
  const endAt = source.indexOf(end)
  if (beginAt === -1 || endAt === -1 || endAt < beginAt) {
    throw new Error(`generated region markers not found or out of order: ${begin}`)
  }
  const head = source.slice(0, beginAt + begin.length)
  const tail = source.slice(endAt)
  return `${head}\n${body}\n${tail}`
}

function renderSkillTable() {
  const lines = []
  lines.push('| 组成 | 在 dsh 上的落点 |')
  lines.push('|---|---|')
  lines.push(
    `| ${upstreamSkills.length} 个上游技能 | \`ctx.skills.registerProvider(...)\` —— 一个指向本包的私有 `
    + '`dsh-skill-filesystem` 实例，位于 `bundledSkillDir`，rank `600`，每个 '
    + '`<skills>/<name>/SKILL.md` 一个候选 |',
  )
  lines.push(
    `| \`using-superpowers\` 引导段 | \`ctx.systemPrompt.section({ name: `
    + `'${manifest.config.defaults.providerName}:bootstrap', order: ${BOOTSTRAP_ORDER} })\`，`
    + '从第一轮起就装配进每一次请求 |',
  )
  // 只列自有技能的名字。名字是派生的，措辞是通用的，
  // 因此新增技能或改写描述都不会让这里过时。
  // 没有自有技能时整行省略：本包的全部技能都来自上游，这一行会变成噪音。
  if (own.size > 0) {
    lines.push(
      `| 本包自有的 ${own.size} 个技能 | `
      + `${[...own].sort().map((n) => `\`${n}\``).join('、')} |`,
    )
  }
  return lines.join('\n')
}

function renderExpectedSkills() {
  const upstreamLines = upstreamSkills.map((s) => `  '${s}',`)
  const ownLines = [...own].sort().map((s) => `  '${s}',`)
  return [
    ...upstreamLines,
    ...(ownLines.length ? ["  // This adapter's own skills (live natively in skills/).", ...ownLines] : []),
  ].join('\n')
}

// ---------------------------------------------------------------------------
// Run
// ---------------------------------------------------------------------------

const patchRel = 'cordis.patch.yml'
emit(patchRel, renderPatch())

for (const [rel, regions] of Object.entries(manifest.regions)) {
  // Skip the manifest's own `$comment` documentation keys.
  if (rel.startsWith('$')) continue
  const full = join(packageRoot, rel)
  if (!existsSync(full)) throw new Error(`region file missing: ${rel}`)
  let source = readFileSync(full, 'utf8')
  for (const region of regions) {
    const body = region.id === 'skill-table' ? renderSkillTable() : renderExpectedSkills()
    source = replaceRegion(source, region, body)
  }
  emit(rel, source)
}

// Copies: master copies kept outside skills/ because a sync rebuilds that tree.
//
// Two categories, and the in-tree one is read through the shared helper so
// generate-artifacts and sync-skills --check cannot disagree about which files
// belong inside skills/:
//   - targets under skills/  → ownContentInSkillsTree()
//   - targets elsewhere      → the manifest directly
const inTreeCopies = ownContentInSkillsTree(packageRoot)
for (const { from, targetRel } of inTreeCopies) {
  emit(join(manifest.skillTree?.root ?? 'skills', targetRel), readFileSync(from, 'utf8'))
}
const inTreeTargets = new Set(inTreeCopies.map((c) => c.targetRel))
for (const [from, to] of Object.entries(manifest.copies)) {
  if (from.startsWith('$') || to.startsWith('$')) continue
  const relUnderRoot = to.startsWith(`${manifest.skillTree?.root ?? 'skills'}/`)
    ? to.slice((manifest.skillTree?.root ?? 'skills').length + 1)
    : undefined
  if (relUnderRoot !== undefined && inTreeTargets.has(relUnderRoot)) continue
  const src = join(packageRoot, from)
  if (!existsSync(src)) throw new Error(`copy source missing: ${from}`)
  emit(to, readFileSync(src, 'utf8'))
}

if (!checkOnly) {
  for (const { full, content } of writes) {
    mkdirSync(dirname(full), { recursive: true })
    writeFileSync(full, content, 'utf8')
  }
}

for (const line of produced) console.log(`[artifacts] ${line}`)
const drifted = produced.filter((l) => l.startsWith('DRIFT'))
if (checkOnly) {
  if (drifted.length > 0) {
    console.error(`\n[artifacts] ${drifted.length} artifact(s) drifted from artifacts.json`)
    console.error('[artifacts] run: node scripts/generate-artifacts.mjs')
    process.exit(1)
  }
  console.log(`\n[artifacts] all ${produced.length} artifacts match artifacts.json`)
} else {
  console.log(`\n[artifacts] ${writes.length} file(s) written, ${produced.length - writes.length} already current`)
  console.log(`[artifacts] skills: ${upstreamSkills.length} upstream + ${own.size} own = ${allSkills.length}`)
}
